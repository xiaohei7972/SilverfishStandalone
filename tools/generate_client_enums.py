"""从客户端 C# 枚举生成只包含成员名和数值的定义。"""

import re
import sys
from pathlib import Path
from tempfile import TemporaryDirectory


ENUM_NAMES = (
    "GAME_TAG", "TAG_ZONE", "TAG_RACE", "TAG_SPELL_SCHOOL", "TAG_CARDTYPE", "TAG_CARD_ALTERNATE_COST",
    "TAG_CARD_SET", "TAG_CLASS", "ErrorType",
)
OUTPUT = Path(__file__).resolve().parents[1] / "src/Silverfish.Domain/Client/ClientEnums.g.cs"
MEMBER = re.compile(r"([A-Za-z_]\w*)(?:\s*=\s*([+-]?(?:0[xX][0-9a-fA-F]+|[0-9]+)))?")


def read_members(path: Path, name: str) -> list[tuple[str, int]]:
    source = re.sub(r"//[^\r\n]*|/\*.*?\*/", "", path.read_text(encoding="utf-8-sig"), flags=re.DOTALL)
    declaration = re.search(rf"\benum\s+{name}\b\s*(?::\s*int\s*)?\{{([^{{}}]*)\}}", source)
    if declaration is None:
        raise ValueError(f"在「{path}」中找不到枚举 {name}。")

    members = {}
    value = -1
    entries = declaration[1].strip().removesuffix(",").split(",")
    for entry in entries:
        match = MEMBER.fullmatch(entry.strip())
        if match is None:
            raise ValueError(f"无法解析枚举 {name} 的成员「{entry.strip()}」。")
        member, explicit = match.groups()
        if member in members:
            raise ValueError(f"枚举 {name} 的成员「{member}」重复。")
        value = value + 1 if explicit is None else int(explicit, 16 if "x" in explicit.lower() else 10)
        if not -(1 << 31) <= value < (1 << 31):
            raise ValueError(f"枚举 {name} 的成员「{member}」超出 int 范围。")
        members[member] = value
    return list(members.items())


def generate(source: Path) -> str:
    lines = [
        "// <auto-generated>",
        "// 由客户端枚举生成。请通过 tools/generate_client_enums.py 更新。",
        "// </auto-generated>",
        "namespace Silverfish.Domain.Client;",
        "",
    ]
    for name in ENUM_NAMES:
        lines.extend([f"public enum {name}", "{"])
        lines.extend(f"    {member} = {value}," for member, value in read_members(source / ("PlayErrors.cs" if name == "ErrorType" else f"{name}.cs"), name))
        lines.extend(["}", ""])
    return "\n".join(lines)


def main() -> int:
    args = sys.argv[1:]
    usage = "用法  python tools/generate_client_enums.py <Assembly-CSharp 目录> [--check]"
    if args in (["-h"], ["--help"]):
        print(usage)
        return 0
    if len(args) not in (1, 2) or args[0].startswith("-") or args[1:] not in ([], ["--check"]):
        print(usage, file=sys.stderr)
        return 2
    source = Path(args[0])

    try:
        content = generate(source)
        if args[1:]:
            if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8-sig") != content:
                print("生成的枚举与客户端源码不一致。", file=sys.stderr)
                return 1
            print(f"{len(ENUM_NAMES)} 个枚举均与客户端源码一致。")
        else:
            OUTPUT.parent.mkdir(parents=True, exist_ok=True)
            with TemporaryDirectory(dir=OUTPUT.parent, prefix=".client-enums-") as directory:
                temporary = Path(directory) / "enums.tmp"
                temporary.write_text(content, encoding="utf-8", newline="\n")
                temporary.replace(OUTPUT)
            print(f"已生成 {len(ENUM_NAMES)} 个客户端枚举到「{OUTPUT}」。")
    except UnicodeError:
        print("同步客户端枚举失败。源文件与生成文件必须使用 UTF-8 编码。", file=sys.stderr)
        return 1
    except (OSError, ValueError) as error:
        detail = str(error) if isinstance(error, ValueError) else f"无法读写「{error.filename or source}」。"
        print(f"同步客户端枚举失败。{detail}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
